import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { resolve } from 'node:path'

const source = new URL('../internal/user/time_zone_catalog_v0600.json', import.meta.url)
const destination = fileURLToPath(new URL('../migrations/00038_expand_time_zone_catalog.sql', import.meta.url))
const legacy = ['UTC', 'Asia/Shanghai', 'Asia/Singapore', 'Asia/Tokyo', 'Europe/London', 'Europe/Paris', 'America/New_York', 'America/Los_Angeles', 'Australia/Sydney']

/** Derives this frozen migration only; future releases need their own source and migration. */
export function renderTimeZoneMigration(zones) {
  if (!Array.isArray(zones) || zones.length === 0 || zones.some((zone, index) => typeof zone !== 'string' || !/^(UTC|[A-Za-z_+-]+(\/[A-Za-z_+-]+)+)$/.test(zone) || (index > 0 && zone <= zones[index - 1])) || legacy.some(zone => !zones.includes(zone))) {
    throw new Error('Invalid versioned time-zone catalog')
  }
  const sqlList = values => values.map(value => `    '${value}'`).join(',\n')
  return `-- Generated by scripts/generate-time-zone-catalog.mjs from the frozen v0600 catalog.
-- +goose Up
alter table user_time_zone_preference
    drop constraint user_time_zone_preference_time_zone_check,
    add constraint user_time_zone_preference_time_zone_check check (time_zone in (
${sqlList(zones)}
    ));

-- +goose Down
-- +goose StatementBegin
lock table user_time_zone_preference in access exclusive mode;
do $$
begin
    if exists (select 1 from user_time_zone_preference where time_zone not in (
${sqlList(legacy)}
    )) then
        raise exception 'cannot restore nine time zones while expanded preferences exist';
    end if;
end;
$$;
alter table user_time_zone_preference
    drop constraint user_time_zone_preference_time_zone_check,
    add constraint user_time_zone_preference_time_zone_check check (time_zone in (
${sqlList(legacy)}
    ));
-- +goose StatementEnd
`
}

/** Creates missing output once, checks equal output, and never replaces historical bytes. */
export async function generateTimeZoneMigration(output = destination, check = false) {
  const text = renderTimeZoneMigration(JSON.parse(await readFile(source, 'utf8')))
  let existing
  try { existing = await readFile(output, 'utf8') }
  catch (error) { if (error.code !== 'ENOENT') throw error }
  if (existing !== undefined) {
    if (existing.replaceAll('\r\n', '\n') !== text) throw new Error('Refusing to overwrite a different historical migration')
  } else {
    if (check) throw new Error('Generated migration is missing')
    await writeFile(output, text, { flag: 'wx' })
  }
  return text
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  try {
    if (process.argv.slice(2).some(arg => arg !== '--check')) throw new Error('Only --check is accepted')
    await generateTimeZoneMigration(destination, process.argv.includes('--check'))
    console.log('Frozen v0.60.0 time-zone migration matches its catalog.')
  } catch (error) {
    console.error(error.message)
    process.exitCode = 1
  }
}
